// Package generate builds CPE's pinned English/root collation data.
package generate

import (
	"bufio"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"fmt"
	"io"
	"slices"
	"strconv"
	"strings"

	"golang.org/x/text/unicode/norm"
)

const sourceHash = "d7cdfab860bf94c6f470c1fae39b81619a12f3a51f80d7cad1ba08404dec3de6"

type mapping struct {
	prefix  []rune
	text    []rune
	weights []uint64
}

// Tables writes Go tables derived from ICU 78.3's FractionalUCA.txt.
// It rejects input that differs from the pinned upstream file.
func Tables(input io.Reader, output io.Writer) error {
	data, err := io.ReadAll(io.LimitReader(
		input,
		2<<20,
	))
	if err != nil {
		return err
	}
	if fmt.Sprintf(
		"%x",
		sha256.Sum256(data),
	) != sourceHash {
		return fmt.Errorf(
			"collation source does not match pinned ICU 78.3 SHA-256 %s",
			sourceHash,
		)
	}
	entries, han, err := parse(data)
	if err != nil {
		return err
	}
	var packed []byte
	packed = binary.AppendUvarint(
		packed,
		uint64(len(han)),
	)
	for _, r := range han {
		packed = binary.AppendUvarint(
			packed,
			uint64(r),
		)
	}
	packed = binary.AppendUvarint(
		packed,
		uint64(len(entries)),
	)
	for _, entry := range entries {
		for _, runes := range [][]rune{
			entry.prefix,
			entry.text,
		} {
			packed = binary.AppendUvarint(
				packed,
				uint64(len(runes)),
			)
			for _, r := range runes {
				packed = binary.AppendUvarint(
					packed,
					uint64(r),
				)
			}
		}
		packed = binary.AppendUvarint(
			packed,
			uint64(len(entry.weights)),
		)
		for _, weight := range entry.weights {
			packed = binary.BigEndian.AppendUint64(
				packed,
				weight,
			)
		}
	}
	var compressed bytes.Buffer
	writer := gzip.NewWriter(&compressed)
	if _, err := writer.Write(packed); err != nil {
		return err
	}
	if err := writer.Close(); err != nil {
		return err
	}
	encoded := base64.StdEncoding.EncodeToString(compressed.Bytes())
	var source strings.Builder
	source.WriteString("// Code generated by go run ./build collation-data; DO NOT EDIT.\n")
	source.WriteString("// ICU 78.3, Unicode 17.0.0. Source SHA-256: " + sourceHash + "\n")
	source.WriteString("// Copyright © 2016-2025 Unicode, Inc. See LICENSE in this directory.\n\n")
	source.WriteString("package pathcollate\n\nconst collationData =\n")
	for len(encoded) > 0 {
		n := min(
			100,
			len(encoded),
		)
		fmt.Fprintf(
			&source,
			"\t%q",
			encoded[:n],
		)
		encoded = encoded[n:]
		if encoded != "" {
			source.WriteString(" +")
		}
		source.WriteByte('\n')
	}
	_, err = io.WriteString(
		output,
		source.String(),
	)
	return err
}

func parse(data []byte) ([]mapping, []rune, error) {
	var han []rune
	scanner := bufio.NewScanner(bytes.NewReader(data))
	scanner.Buffer(
		nil,
		100000,
	)
	for scanner.Scan() {
		line := scanner.Text()
		if !strings.HasPrefix(
			line,
			"[radical ",
		) || line == "[radical end]" {
			continue
		}
		_, characters, ok := strings.Cut(
			line,
			":",
		)
		if !ok {
			return nil, nil, fmt.Errorf(
				"invalid radical line: %s",
				line,
			)
		}
		runes := []rune(strings.TrimSuffix(
			characters,
			"]",
		))
		for i := 0; i < len(runes); i++ {
			first, last := runes[i], runes[i]
			if i+2 < len(runes) && runes[i+1] == '-' {
				last = runes[i+2]
				i += 2
			}
			for r := first; r <= last; r++ {
				han = append(
					han,
					r,
				)
			}
		}
	}
	if err := scanner.Err(); err != nil {
		return nil, nil, err
	}
	hans := make(
		map[rune]uint64,
		len(han),
	)
	// ICU reserves enough lead bytes below FE for all Han weights and their gaps.
	lead := 0xfe - (len(han)*2+4+254*254-1)/(254*254)
	for i, r := range han {
		// ICU's root uses radical/stroke order, with two primary slots per Han character.
		offset := i * 2
		primary := uint32((lead+offset/(254*254))<<24 | (2+offset/254%254)<<16 | (2+offset%254)<<8)
		hans[r] = uint64(primary)<<32 | 0x05000500
	}
	var entries []mapping
	scanner = bufio.NewScanner(bytes.NewReader(data))
	scanner.Buffer(
		nil,
		100000,
	)
	for scanner.Scan() {
		line, _, _ := strings.Cut(
			scanner.Text(),
			"#",
		)
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(
			line,
			"[",
		) {
			continue
		}
		key, weights, ok := strings.Cut(
			line,
			";",
		)
		if !ok {
			return nil, nil, fmt.Errorf(
				"invalid collation record: %s",
				line,
			)
		}
		prefix, text, hasPrefix := strings.Cut(
			key,
			"|",
		)
		if !hasPrefix {
			text, prefix = prefix, ""
		}
		p, err := codePoints(prefix)
		if err != nil {
			return nil, nil, err
		}
		s, err := codePoints(text)
		if err != nil || len(s) == 0 {
			return nil, nil, fmt.Errorf(
				"invalid collation string %q: %w",
				text,
				err,
			)
		}
		if s[0] == 0xfdd0 || s[0] >= 0xfffd && s[0] <= 0xffff {
			continue // ICU reserves these boundary/special mappings.
		}
		// ICU4X also drops precomposed characters; NFD strings use the underlying mappings.
		if !norm.NFD.IsNormalString(string(s[0])) {
			continue
		}
		entry := mapping{
			prefix: []rune(norm.NFD.String(string(p))),
			text:   []rune(norm.NFD.String(string(s))),
		}
		for weights = strings.TrimSpace(weights); weights != ""; weights = strings.TrimSpace(weights) {
			if weights[0] != '[' {
				return nil, nil, fmt.Errorf(
					"invalid collation weights: %s",
					weights,
				)
			}
			body, rest, ok := strings.Cut(
				weights[1:],
				"]",
			)
			if !ok {
				return nil, nil, fmt.Errorf(
					"unterminated collation weights: %s",
					weights,
				)
			}
			parts := strings.Split(
				body,
				",",
			)
			var weight uint64
			if strings.HasPrefix(
				parts[0],
				"U+",
			) {
				r, err := strconv.ParseUint(
					parts[0][2:],
					16,
					32,
				)
				if err != nil {
					return nil, nil, err
				}
				var found bool
				weight, found = hans[rune(r)]
				if !found {
					return nil, nil, fmt.Errorf(
						"unknown Han reference: %s",
						parts[0],
					)
				}
				if len(parts) == 3 {
					w, err := parseWeight(
						parts[1],
						2,
					)
					if err != nil {
						return nil, nil, err
					}
					weight = weight&0xffffffff0000ffff | uint64(w)<<16
				}
				if len(parts) > 1 {
					w, err := parseWeight(
						parts[len(parts)-1],
						2,
					)
					if err != nil {
						return nil, nil, err
					}
					weight = weight&0xffffffffffff0000 | uint64(w)
				}
			} else {
				if len(parts) != 3 {
					return nil, nil, fmt.Errorf(
						"invalid collation element: %s",
						body,
					)
				}
				for i, size := range []int{
					4,
					2,
					2,
				} {
					w, err := parseWeight(
						parts[i],
						size,
					)
					if err != nil {
						return nil, nil, err
					}
					weight = weight<<uint(size*8) | uint64(w)
				}
			}
			entry.weights = append(
				entry.weights,
				weight,
			)
			weights = rest
		}
		if len(s) == 2 && s[0] == 0xfdd1 {
			switch s[1] {
			case 0xfdd0:
				entry.weights = []uint64{
					0xfe04020005000500,
				}
			case 0xac00:
				entry.text = []rune{
					0x110000,
				}
			}
		}
		entries = append(
			entries,
			entry,
		)
	}
	if err := scanner.Err(); err != nil {
		return nil, nil, err
	}
	slices.SortFunc(
		entries,
		func(a, b mapping) int {
			if order := strings.Compare(
				string(a.text),
				string(b.text),
			); order != 0 {
				return order
			}
			return strings.Compare(
				string(a.prefix),
				string(b.prefix),
			)
		},
	)
	return entries, han, nil
}

func codePoints(s string) ([]rune, error) {
	var runes []rune
	for field := range strings.FieldsSeq(s) {
		r, err := strconv.ParseUint(
			field,
			16,
			32,
		)
		if err != nil || r > 0x10ffff {
			return nil, fmt.Errorf(
				"invalid code point %q",
				field,
			)
		}
		runes = append(
			runes,
			rune(r),
		)
	}
	return runes, nil
}

func parseWeight(s string, width int) (uint32, error) {
	fields := strings.Fields(s)
	if len(fields) > width {
		return 0, fmt.Errorf(
			"collation weight exceeds %d bytes: %s",
			width,
			s,
		)
	}
	var weight uint32
	for _, field := range fields {
		b, err := strconv.ParseUint(
			field,
			16,
			8,
		)
		if err != nil {
			return 0, err
		}
		weight = weight<<8 | uint32(b)
	}
	return weight << uint((width-len(fields))*8), nil
}
